const singularEnglish: Partial<Record<MessageKey, string>> = {
  selectedSources: "{count} source selected",
  timelineTotal: "{count} article over {days} UTC days",
  dayCount: "{date} UTC: {count} article. Open this day",
  articlesUnit: "article",
  updatesUnit: "new update",
  channels: "official channel",
  resultCount: "{count} result · {loaded} shown",
  updateCount: "{count} update",
  syncedCount: "{count} article synced",
  loaded: "{count} loaded · {total} matching article",
};
export function translate(
  locale: Locale,
  key: MessageKey,
  values: Record<string, string | number> = {},
): string {
  const count = key === "loaded" ? values.total : values.count;
  const message = locale === "en" && count === 1
    ? singularEnglish[key] ?? en[key]
    : (locale === "en" ? en : zh)[key];
  return message.replace(
    /\{(\w+)\}/g,
    (_, name: string) => String(values[name] ?? `{${name}}`),
  );
}
const categoryKeys: Record<string, MessageKey> = {
  全部资讯: "all",
  模型进展: "models",
  研究前沿: "research",
  开发工具: "tools",
  产业动态: "industry",
  安全治理: "safety",
  具身智能: "robotics",
};
export function categoryLabel(locale: Locale, category: string): string {
  return categoryKeys[category]
    ? translate(locale, categoryKeys[category])
    : category;
}
export type Translator = (
  key: MessageKey,
  values?: Record<string, string | number>,
) => string;

export function scheduleLabel(locale: Locale, schedule: string): string {
  if (!schedule) return translate(locale, "connecting");
  if (schedule === "每小时自动更新") return translate(locale, "scheduleHourly");
  if (schedule === "尚未启用") return translate(locale, "scheduleDisabled");
  return schedule;
}
